export type PhotoId = keyof typeof photoRecords;

export function photo(id: PhotoId): ImageAsset {
  const record = photoRecords[id];
  return { src: `/images/photos/${id}.jpg`, width: record.width, height: record.height, alt: record.alt };
}

export function listPhotoCredits(): readonly PhotoCredit[] {
  return (Object.keys(photoRecords) as PhotoId[]).map((id) => ({
    id,
    src: `/images/photos/${id}.jpg`,
    ...photoRecords[id].credit,
  }));
}
